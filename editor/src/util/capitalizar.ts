const ROMANOS = new Map([
  ["I", 1],
  ["V", 5],
  ["X", 10],
  ["L", 50],
  ["C", 100],
  ["D", 500],
  ["M", 1000],
]);

/**
 * Valor do numeral romano (`romanToInt` do legado, com a mesma esquisitice: a palavra inteira em maiuscula
 * cujas letras sejam todas romanas, como "CIVIL", conta como romana; com qualquer letra fora do conjunto o
 * resultado e NaN, que nao e > 0).
 */
export function valorRomano(s: string): number {
  let resultado = 0;
  const letras = s.split("");
  letras.forEach((e, i) => {
    const atual = ROMANOS.get(e) as number;
    const proximo = ROMANOS.get(letras[i + 1] as string) as number;
    resultado += atual < proximo ? -atual : atual;
  });
  return resultado;
}

export function capitalizar(texto: string): string {
  if (!texto || typeof texto !== "string" || texto.trim() === "") return "";
  if (!texto.includes(" ")) return (texto[0] as string).toUpperCase() + texto.substring(1).toLowerCase();
  return texto
    .split(" ")
    .map((s, indice) => {
      if (s === "") return s;
      if (EXCECOES.has(s.toLowerCase()) && indice !== 0) return s.toLowerCase();
      if (valorRomano(s) > 0) return s.toUpperCase();
      return (s[0] as string).toUpperCase() + s.substring(1).toLowerCase();
    })
    .join(" ");
}
