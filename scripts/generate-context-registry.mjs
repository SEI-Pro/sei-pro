/**
 * Gera registries estáticos por contexto a partir dos descritores de feature.
 *
 * O browser não pode descobrir arquivos. A descoberta ocorre aqui, em Node,
 * e os artefatos versionados são conferidos pelo build para evitar uma segunda
 * lista manual de features. Só capacidades `exclusive` entram na raiz:
 * uma capability `wired` ainda tem caminho paralelo e não pode ser instalada
 * duas vezes.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { REPO_ROOT, scanFeatureDescriptors } from './lib/scan-feature-descriptors.mjs';

const root = REPO_ROOT;

// Contextos que já possuem uma composição ESM exclusiva. Novos contextos só
// entram aqui depois que sua rota legada foi removida do manifest.
export const GENERATED_CONTEXTS = Object.freeze(['login', 'db', 'lista']);

function camelCase(id) {
    return id.replace(/-([a-z0-9])/g, (_, char) => char.toUpperCase());
}

function pascalCase(id) {
    return camelCase(id).replace(/^./, (char) => char.toUpperCase());
}

export function registryPath(context, rootDir = root) {
    return path.join(rootDir, `src/generated/${context}-feature-registry.ts`);
}

export function generateContextRegistry(context, rootDir = root) {
    if (!GENERATED_CONTEXTS.includes(context)) {
        throw new Error(`contexto sem registry gerado: ${context}`);
    }

    const descriptors = scanFeatureDescriptors(rootDir)
        .filter((descriptor) =>
            descriptor.maturity === 'exclusive' && descriptor.contexts.includes(context)
        )
        .sort((a, b) => a.id.localeCompare(b.id));

    const imports = descriptors.map((descriptor) =>
        `import ${camelCase(descriptor.id)} from '../features/${descriptor.id}/feature.js';`
    );
    const names = descriptors.map((descriptor) => camelCase(descriptor.id));
    const prefix = pascalCase(context);
    const text = [
        '// Generated by scripts/generate-context-registry.mjs. Do not edit manually.',
        "import { registerFeatures } from '../app/feature-registry.js';",
        ...imports,
        '',
        `export const ${prefix.toUpperCase()}_EXCLUSIVE_FEATURES = Object.freeze([${names.join(', ')}]);`,
        '',
        `export function register${prefix}ExclusiveFeatures() {`,
        `    registerFeatures(${prefix.toUpperCase()}_EXCLUSIVE_FEATURES);`,
        '}',
        ''
    ].join('\n');
    return { context, descriptors, text };
}

// Kept as a named export for callers that used the first lista-only pilot API.
export function generateListaRegistry(rootDir = root) {
    return generateContextRegistry('lista', rootDir);
}

function allRegistries(rootDir = root) {
    return GENERATED_CONTEXTS.map((context) => generateContextRegistry(context, rootDir));
}

function main() {
    const write = process.argv.includes('--write');
    const check = process.argv.includes('--check');
    const generated = allRegistries();

    if (write) {
        for (const registry of generated) {
            const output = registryPath(registry.context);
            fs.mkdirSync(path.dirname(output), { recursive: true });
            fs.writeFileSync(output, registry.text);
            console.log(`registry:write ${registry.context} — ${registry.descriptors.length} exclusive feature(s)`);
        }
        return;
    }
    if (check) {
        for (const registry of generated) {
            const output = registryPath(registry.context);
            const current = fs.existsSync(output) ? fs.readFileSync(output, 'utf8') : null;
            if (current !== registry.text) {
                console.error(`${registry.context} registry is stale; run: npm run registry:write`);
                process.exit(1);
            }
            console.log(`registry:check ${registry.context} — ${registry.descriptors.length} exclusive feature(s)`);
        }
        return;
    }
    process.stdout.write(generated.map(({ text }) => text).join('\n'));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    main();
}
