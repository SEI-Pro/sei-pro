/**
 * Gera registries estáticos por contexto a partir dos descritores de feature.
 *
 * O browser não pode descobrir arquivos. A descoberta ocorre aqui, em Node,
 * e o artefato versionado é conferido pelo build para evitar uma segunda lista
 * manual de features. Neste estágio só capacidades `exclusive` entram na raiz:
 * uma capability `wired` ainda tem caminho paralelo e não pode ser instalada
 * duas vezes.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { REPO_ROOT, scanFeatureDescriptors } from './lib/scan-feature-descriptors.mjs';

const root = REPO_ROOT;
const context = 'lista';
const output = path.join(root, 'src/generated/lista-feature-registry.ts');

function camelCase(id) {
    return id.replace(/-([a-z0-9])/g, (_, char) => char.toUpperCase());
}

export function generateListaRegistry(rootDir = root) {
    const descriptors = scanFeatureDescriptors(rootDir)
        .filter((descriptor) =>
            descriptor.maturity === 'exclusive' && descriptor.contexts.includes(context)
        )
        .sort((a, b) => a.id.localeCompare(b.id));

    const imports = descriptors.map((descriptor) =>
        `import ${camelCase(descriptor.id)} from '../features/${descriptor.id}/feature.js';`
    );
    const names = descriptors.map((descriptor) => camelCase(descriptor.id));
    const text = [
        '// Generated by scripts/generate-context-registry.mjs. Do not edit manually.',
        "import { registerFeatures } from '../app/feature-registry.js';",
        ...imports,
        '',
        `export const LISTA_EXCLUSIVE_FEATURES = Object.freeze([${names.join(', ')}]);`,
        '',
        'export function registerListaExclusiveFeatures() {',
        '    registerFeatures(LISTA_EXCLUSIVE_FEATURES);',
        '}',
        ''
    ].join('\n');
    return { descriptors, text };
}

function main() {
    const write = process.argv.includes('--write');
    const check = process.argv.includes('--check');
    const { text, descriptors } = generateListaRegistry();
    const current = fs.existsSync(output) ? fs.readFileSync(output, 'utf8') : null;

    if (write) {
        fs.mkdirSync(path.dirname(output), { recursive: true });
        fs.writeFileSync(output, text);
        console.log(`registry:write lista — ${descriptors.length} exclusive feature(s)`);
        return;
    }
    if (check) {
        if (current !== text) {
            console.error('lista registry is stale; run: npm run registry:write');
            process.exit(1);
        }
        console.log(`registry:check lista — ${descriptors.length} exclusive feature(s)`);
        return;
    }
    process.stdout.write(text);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    main();
}
